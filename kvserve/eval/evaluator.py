"""
KVServe Evaluator - Compatible with lm-evaluation-harness LM interface
"""

import asyncio
import logging
from typing import List, Tuple, Optional, Any

from transformers import AutoTokenizer

from kvserve.engine.backend import PDBackend
from kvserve.engine.utils import Request

eval_logger = logging.getLogger(__name__)

# Try to import LM base class from lm-eval
try:
    from lm_eval.api.model import LM
    from abc import ABC
    _LM_BASE = LM
    _HAS_LM_BASE = True
except ImportError:
    # If lm-eval is not installed, use ABC as fallback
    from abc import ABC
    _LM_BASE = ABC
    _HAS_LM_BASE = False


class KVServeEvaluator(_LM_BASE):
    """
    KVServe evaluator compatible with lm-evaluation-harness LM interface
    
    Implements the three core methods required by lm-eval:
    - loglikelihood: Compute log-likelihood of continuations
    - loglikelihood_rolling: Compute full log-likelihood for perplexity
    - generate_until: Generate text until stopping sequences
    """
    
    def __init__(
        self,
        backend: PDBackend,
        tokenizer: Optional[Any] = None,
        model_path: Optional[str] = None,
    ):
        """
        Initialize KVServe evaluator
        
        Args:
            backend: Initialized PDBackend instance
            tokenizer: Tokenizer instance (optional, will load from model_path if not provided)
            model_path: Path to model (for loading tokenizer if tokenizer not provided)
        """
        # Initialize base class if it's LM
        if _HAS_LM_BASE:
            super().__init__()
        
        self.backend = backend
        self.model_path = model_path or backend.model_path
        
        # Load tokenizer if not provided
        if tokenizer is None:
            self.tokenizer = AutoTokenizer.from_pretrained(
                self.model_path,
                trust_remote_code=True
            )
        else:
            self.tokenizer = tokenizer
        
        # Track pending requests
        self._pending_requests = {}
        self._request_counter = 0
        
        # Ensure backend is started
        self._loop = None
        self._backend_started = False
    
    async def _ensure_backend_started(self):
        """Ensure backend is started"""
        if not self._backend_started:
            await self.backend.start()
            await asyncio.sleep(2)  # Wait for stability
            self._backend_started = True
    
    def loglikelihood(self, requests) -> List[Tuple[float, bool]]:
        """
        Compute log-likelihood of generating a continuation from a context.
        
        Args:
            requests: list[Instance]
                A list of Instance objects with property `args` which returns a tuple (context, continuation).
                context: str - Context string
                continuation: str - The continuation over which log likelihood will be calculated
        
        Returns:
            list[tuple[float, bool]]
                A list of pairs (logprob, isgreedy)
                logprob: float - The log probability of continuation
                isgreedy: bool - Whether continuation would be generated by greedy sampling
        """
        try:
            # Check if we're in an async context
            loop = asyncio.get_running_loop()
            # If we're in an async context, use thread pool to run in separate event loop
            import concurrent.futures
            with concurrent.futures.ThreadPoolExecutor() as executor:
                future = executor.submit(lambda: asyncio.run(self._loglikelihood_async(requests)))
                return future.result()
        except RuntimeError:
            # No running loop, safe to use asyncio.run
            return asyncio.run(self._loglikelihood_async(requests))
    
    async def _loglikelihood_async(self, requests) -> List[Tuple[float, bool]]:
        """Async implementation of loglikelihood"""
        await self._ensure_backend_started()
        
        results = []
        
        # Get a worker from prefill engine to compute logprobs
        # We use prefill engine workers as they have the model loaded
        if not self.backend.prefill_engine.workers:
            raise RuntimeError("No workers available for loglikelihood computation")
        
        # Use the first worker
        worker = self.backend.prefill_engine.workers[0]
        
        for instance in requests:
            # Extract context and continuation from instance
            # Instance has property 'args' that returns tuple (context, continuation)
            if hasattr(instance, 'args'):
                args = instance.args
                if isinstance(args, tuple) and len(args) >= 2:
                    context, continuation = args[0], args[1]
                else:
                    context, continuation = args
            elif hasattr(instance, 'arguments'):
                # Alternative: use 'arguments' property
                args = instance.arguments
                if isinstance(args, tuple) and len(args) >= 2:
                    context, continuation = args[0], args[1]
                else:
                    context, continuation = args
            else:
                # Fallback: assume instance is a tuple
                context, continuation = instance
            
            # Tokenize
            context_tokens = self.tokenizer.encode(context, add_special_tokens=False)
            if not isinstance(context_tokens, list):
                context_tokens = context_tokens.tolist()
            
            continuation_tokens = self.tokenizer.encode(continuation, add_special_tokens=False)
            if not isinstance(continuation_tokens, list):
                continuation_tokens = continuation_tokens.tolist()
            
            # Handle empty context (use prefix token)
            if len(context_tokens) == 0:
                prefix_token_id = self.tokenizer.bos_token_id if self.tokenizer.bos_token_id is not None else self.tokenizer.eos_token_id
                if prefix_token_id is not None:
                    # Check if continuation starts with prefix token
                    if continuation_tokens and continuation_tokens[0] == prefix_token_id:
                        context_tokens = [continuation_tokens[0]]
                        continuation_tokens = continuation_tokens[1:]
                    else:
                        context_tokens = [prefix_token_id]
            
            # Allocate blocks through block_manager (like normal requests)
            full_tokens = context_tokens + continuation_tokens
            temp_request_id = f"logprob_{self._request_counter}"
            self._request_counter += 1
            
            temp_request = Request(
                request_id=temp_request_id,
                prompt="",  # Not used for block allocation
                max_tokens=1,
            )
            # Set prompt_token_ids for block calculation
            temp_request.prompt_token_ids = full_tokens
            
            # Allocate blocks
            block_manager = self.backend.prefill_engine.block_manager
            block_manager.allocate_blocks(temp_request)
            block_ids = block_manager.get_block_table(temp_request_id)
            
            try:
                # Compute logprobs using worker with allocated blocks
                logprob, isgreedy = await worker.compute_logprobs.remote(
                    context_tokens, continuation_tokens, block_ids
                )
                
                results.append((logprob, isgreedy))
            finally:
                # Always free blocks after computation
                if temp_request_id in block_manager.block_table:
                    block_manager.free_blocks(temp_request_id)
        
        return results
    
